import type {
  FilmRecipe,
  SonyCreativeLook,
  SonyCreativeStyle,
  SonyPictureProfile,
} from '../types'

function pp(
  partial: Omit<SonyPictureProfile, 'colorMode' | 'saturation' | 'colorPhase'> & {
    saturation?: number
    colorPhase?: number
    colorMode?: SonyPictureProfile['colorMode']
  },
): SonyPictureProfile {
  return {
    colorMode: 'Black & White',
    saturation: partial.saturation ?? -32,
    colorPhase: partial.colorPhase ?? 0,
    ...partial,
  }
}

function look(
  p: Omit<SonyCreativeLook, 'look' | 'saturation'> & { saturation?: number },
): SonyCreativeLook {
  return { look: 'BW', saturation: 0, ...p }
}

function style(
  p: Omit<SonyCreativeStyle, 'style' | 'saturation'> & { saturation?: number },
): SonyCreativeStyle {
  return { style: 'Black & White', saturation: 0, ...p }
}

