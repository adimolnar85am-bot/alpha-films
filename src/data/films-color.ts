function depth(p: Partial<ColorDepth>): ColorDepth {
  return { r: 0, g: 0, b: 0, c: 0, m: 0, y: 0, ...p }
}

function pp(
  partial: Omit<SonyPictureProfile, 'colorMode'> & {
    colorMode?: SonyPictureProfile['colorMode']
  },
): SonyPictureProfile {
  return {
    colorMode: 'Still',
    ...partial,
  }
}

function look(
  lookName: SonyCreativeLook['look'],
  p: Omit<SonyCreativeLook, 'look'>,
): SonyCreativeLook {
  return { look: lookName, ...p }
}

function style(
  styleName: SonyCreativeStyle['style'],
  p: Omit<SonyCreativeStyle, 'style'>,
): SonyCreativeStyle {
  return { style: styleName, ...p }
}

